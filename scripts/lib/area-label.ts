/* 괄호 동 없는 주소의 도로명 직접 판정 — 최근접 폴백(1.5km)도 놓치는 외곽 소수 */
const AREA_BY_ROAD: Record<string, string> = {
  "강북구|도봉로 62": "미아",
  "송파구|백제고분로19길": "석촌",
};

export function dongOf(address: string | null | undefined): string | null {
  const m = (address ?? "").match(/\(([가-힣0-9]+)/);
  if (!m) return null;
  return /(동|가)\d*$/.test(m[1]) ? m[1] : null;
}

export function areaLabelOf(
  address: string | null | undefined,
  district: string | null | undefined,
): string | null {
  if (!district) return null;
  const dong = dongOf(address);
  if (dong) return AREA_BY_DONG[`${district}|${dong}`] ?? null;
  const road = Object.entries(AREA_BY_ROAD).find(
    ([key]) =>
      key.startsWith(`${district}|`) &&
      (address ?? "").includes(key.split("|")[1]),
  );
  return road?.[1] ?? null;
}

type AreaPoint = {
  lat: number | null;
  lng: number | null;
  areaLabel: string | null;
};

const NEAREST_MAX_METERS = 1500;

/* 사전 미적중 매장은 라벨 확정된 최근접 매장의 상권을 상속 — 괄호 동 없는 주소 폴백 */
export function inheritNearestArea<T extends AreaPoint>(rows: T[]): T[] {
  const labeled = rows.filter(
    (r) => r.areaLabel && r.lat !== null && r.lng !== null,
  );
  return rows.map((row) => {
    if (row.areaLabel || row.lat === null || row.lng === null) return row;
    let best: T | null = null;
    let bestDist = Infinity;
    for (const cand of labeled) {
      const dLat = (cand.lat! - row.lat) * 111_000;
      const dLng =
        (cand.lng! - row.lng) * 111_000 * Math.cos((row.lat * Math.PI) / 180);
      const dist = Math.hypot(dLat, dLng);
      if (dist < bestDist) {
        bestDist = dist;
        best = cand;
      }
    }
    return best && bestDist <= NEAREST_MAX_METERS
      ? { ...row, areaLabel: best.areaLabel }
      : row;
  });
}
